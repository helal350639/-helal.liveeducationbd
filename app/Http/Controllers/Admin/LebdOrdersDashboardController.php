<?php
namespace App\Http\Controllers\Admin;

use App\Http\Controllers\Controller;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Schema;

class LebdOrdersDashboardController extends Controller
{
    private function ensureAdmin(Request $request): void
    {
        // Web-admin guard only. A student session alone is NEVER enough.
        $user = \Illuminate\Support\Facades\Auth::guard('web')->user();
        abort_unless($user, 403, 'Admin access only.');
        try {
            $role = $user->authRole()->name ?? null;
        } catch (\Throwable $e) {
            abort(403, 'Admin access only.');
        }
        abort_unless(in_array($role, ['Admin', 'SuperAdmin'], true), 403, 'Admin access only.');
    }

    public function index() { 
        $this->ensureAdmin(request()); 
        return redirect()->route('admin.lebd-orders.video', ['source'=>'all', 'status'=>'all']); 
        }

    public function batch(Request $request)
    {
        $this->ensureAdmin($request);
        $source = in_array($request->query('source'), ['all','ssl','referral'], true) ? $request->query('source') : 'all';
        $status = in_array($request->query('status'), ['all','paid','pending'], true) ? $request->query('status') : 'all';
        $range = $request->query('range') === 'all' ? 'all' : 'day';
        $validated = $request->validate(['date'=>'nullable|date_format:Y-m-d', 'order'=>'nullable|integer|min:1']);
        $data = compact('source','status','range') + [
            'section'=>'batch','orders'=>null,'notice'=>null,'selectedDate'=>null,
            'reportCount'=>0,'reportTotal'=>0,'paidTotal'=>0,'pendingTotal'=>0,
            'reportLabel'=>'', 'batchOrderDetail'=>null
        ];
        if (!Schema::hasTable('orders') || !Schema::hasTable('students') || !Schema::hasTable('batches') || !Schema::hasTable('departments')) {
            $data['notice']='Batch order reporting tables are not available.';
            return view('admin.lebd-orders.index',$data);
        }
        $sourceFilter = static function ($q) use ($source) {
            // LEBDBR is the dedicated Referral Batch transaction prefix.
            // Existing SSLCommerz batch transaction IDs were generated by uniqid().
            if ($source === 'referral') $q->where('o.transaction_id','like','LEBDBR%');
            elseif ($source === 'ssl') $q->where('o.transaction_id','not like','LEBDBR%');
        };
        $last = DB::table('orders as o')->whereNotNull('o.created_at')->where($sourceFilter)->max('o.created_at');
        $date = $validated['date'] ?? ($last ? substr((string)$last,0,10) : now('Asia/Dhaka')->toDateString());
        $data['selectedDate']=$date;
        $data['reportLabel']=$range==='all'?'All Dates':$date;
        $query=DB::table('orders as o')
            ->leftJoin('students as s','s.id','=','o.student_id')
            ->leftJoin('batches as b','b.id','=','o.batch_id')
            ->leftJoin('departments as d','d.id','=','o.department_id')
            ->select('o.*','s.name as student_name','s.email as student_email','s.contact as student_contact',
                'b.name as batch_name','d.name as department_name')
            ->where($sourceFilter);
        if ($range === 'day') $query->whereBetween('o.created_at',[$date.' 00:01:00',$date.' 23:59:59']);
        if ($status === 'paid') $query->whereIn('o.status',['Processing','Complete']);
        elseif ($status === 'pending') $query->where('o.status','Pending');
        $summary=(clone $query)->reorder()->select(DB::raw("COUNT(*) AS order_count, COALESCE(SUM(CASE WHEN o.status IN ('Processing','Complete') THEN o.amount ELSE 0 END),0) AS paid_total, COALESCE(SUM(CASE WHEN o.status = 'Pending' THEN o.amount ELSE 0 END),0) AS pending_total"))->first();
        $data['reportCount']=(int)($summary->order_count??0);
        $data['paidTotal']=round((float)($summary->paid_total??0),2);
        $data['pendingTotal']=round((float)($summary->pending_total??0),2);
        $data['reportTotal']=$data['paidTotal'];
        $data['orders']=$query->orderByDesc('o.created_at')->orderByDesc('o.id')->paginate(10)->withQueryString();
        if (!empty($validated['order'])) {
            $data['batchOrderDetail']=DB::table('orders as o')
                ->leftJoin('students as s','s.id','=','o.student_id')
                ->leftJoin('batches as b','b.id','=','o.batch_id')
                ->leftJoin('departments as d','d.id','=','o.department_id')
                ->select('o.*','s.name as student_name','s.email as student_email','s.contact as student_contact',
                    'b.name as batch_name','d.name as department_name')
                ->where('o.id',$validated['order'])->first();
        }
        return view('admin.lebd-orders.index',$data);
    }

    public function video(Request $request)
    {
        $this->ensureAdmin($request);
        // Read-only reporting. Defaults to ALL statuses on the LATEST DATE containing
        // an SSLCommerz order; never defaults to today with no entries.
        $source = in_array($request->query('source'), ['all','ssl','referral'], true) ? $request->query('source') : 'all';
        $status = in_array($request->query('status'), ['all','paid','pending'], true) ? $request->query('status') : 'all';
        $range = $request->query('range') === 'all' ? 'all' : 'day';
        $validated = $request->validate(['date' => 'nullable|date_format:Y-m-d']);
        $prefix = $source === 'referral' ? 'LEBDR%' : ($source === 'ssl' ? 'LEBDP%' : null);
        $latest = null;
        if (Schema::hasTable('lebd_premium_class_orders')) {
            // Match stored MySQL timestamps: do not apply an unverified timezone shift.
            $latest = DB::table('lebd_premium_class_orders')
                ->when($prefix !== null, function ($q) use ($prefix) { $q->where('tran_id','like',$prefix); })->max('created_at');
        }
        $date = $validated['date'] ?? ($latest ? substr((string)$latest,0,10) : now('Asia/Dhaka')->toDateString());
        $data = compact('source','status','range');
        $data += ['section'=>'video','orders'=>null,'notice'=>null,'selectedDate'=>$date,
            'reportCount'=>0,'reportTotal'=>0,'paidTotal'=>0,'pendingTotal'=>0,
            'reportLabel'=>$range === 'all' ? 'All Dates' : $date];
        if (!Schema::hasTable('lebd_premium_class_orders')) {
            $data['notice'] = 'Premium orders table not found.';
            return view('admin.lebd-orders.index',$data);
        }
        $query = DB::table('lebd_premium_class_orders as o')
            ->leftJoin('students as s','s.id','=','o.student_id')
            ->leftJoin('lebd_premium_class_packages as p','p.id','=','o.package_id')
            ->select('o.*','s.name as student_name','s.email as student_email',
                's.contact as student_contact','p.name as package_name')
            ->when($prefix !== null, function ($q) use ($prefix) { $q->where('o.tran_id','like',$prefix); });
        if ($range === 'day') {
            // User-requested 12:01:00 AM to 11:59:59 PM, based on stored order date.
            $query->whereBetween('o.created_at',[$date.' 00:01:00',$date.' 23:59:59']);
        }
        if ($status !== 'all') $query->where('o.status',$status);
        $summary = (clone $query)->reorder()->select(DB::raw("COUNT(*) AS order_count, COALESCE(SUM(CASE WHEN o.status = 'paid' THEN o.amount ELSE 0 END),0) AS paid_total, COALESCE(SUM(CASE WHEN o.status = 'pending' THEN o.amount ELSE 0 END),0) AS pending_total"))->first();
        $data['reportCount'] = (int)($summary->order_count ?? 0);
        $data['paidTotal'] = round((float)($summary->paid_total ?? 0),2);
        $data['pendingTotal'] = round((float)($summary->pending_total ?? 0),2);
        // Only verified PAID revenue counts as collected amount.
        $data['reportTotal'] = $data['paidTotal'];
        $data['orders'] = $query->orderByDesc('o.created_at')->orderByDesc('o.id')
            ->paginate(10)->withQueryString();
        return view('admin.lebd-orders.index',$data);
    }


    // E-Book orders: report only, never change payment status or entitlements here.
    public function ebook(Request $request)
    {
        $this->ensureAdmin($request);
        if (!Schema::hasTable('lebd_ebook_payment_orders')) {
            return view('admin.lebd-orders.ebook', ['orders'=>null, 'totals'=>null,
                'notice'=>'E-Book payment orders table পাওয়া যায়নি।']);
        }
        $query = DB::table('lebd_ebook_payment_orders as o')
            ->leftJoin('students as s','s.id','=','o.student_id')
            ->leftJoin('lebd_ebook_categories as c','c.id','=','o.category_id')
            ->select('o.*','s.name as student_name','s.email as student_email',
                's.contact as student_contact','c.name as book_name','c.kind as book_kind');
        $status = (string)$request->query('status','all');
        if (in_array($status,['Complete','Pending','Failed','Canceled'],true)) {
            $query->where('o.status',$status);
        }
        $source = (string)$request->query('source','all');
        // E-Book referral purchases also use EBK... IDs. The dedicated marker,
        // saved by EBookReferralController after a successful debit, is authoritative.
        if ($source === 'referral') {
            $query->where(function ($q) {
                $q->where('o.gateway_validation_id', 'REFERRAL_BALANCE')
                  ->orWhere('o.transaction_id', 'like', 'EBR%');
            });
        }
        if ($source === 'ssl') {
            $query->where(function ($q) {
                $q->where(function ($inner) {
                    $inner->whereNull('o.gateway_validation_id')
                          ->orWhere('o.gateway_validation_id', '<>', 'REFERRAL_BALANCE');
                })->where('o.transaction_id', 'not like', 'EBR%');
            });
        }
        if ($request->filled('date')) {
            $date=(string)$request->query('date');
            if (preg_match('/^\d{4}-\d{2}-\d{2}$/',$date)) $query->whereDate('o.created_at',$date);
        }
        if ($request->filled('search')) {
            $term=trim((string)$request->query('search'));
            $query->where(function($q)use($term){
                $q->where('o.transaction_id','like','%'.$term.'%')
                  ->orWhere('s.name','like','%'.$term.'%')
                  ->orWhere('s.email','like','%'.$term.'%')
                  ->orWhere('c.name','like','%'.$term.'%');
            });
        }
        $totals=(clone $query)->reorder()->select(DB::raw("COUNT(*) AS total, COALESCE(SUM(CASE WHEN o.status = 'Complete' THEN o.amount ELSE 0 END),0) AS paid, COALESCE(SUM(CASE WHEN o.status = 'Pending' THEN o.amount ELSE 0 END),0) AS pending"))->first();
        return view('admin.lebd-orders.ebook',[
          'orders'=>$query->orderByDesc('o.id')->paginate(10)->withQueryString(),
          'totals'=>$totals,'notice'=>null,
        ]);
    }

    public function videoShow(int $order)
    {
        $this->ensureAdmin(request());
        abort_unless(Schema::hasTable('lebd_premium_class_orders'),404);
        $row = DB::table('lebd_premium_class_orders as o')
            ->leftJoin('students as s','s.id','=','o.student_id')
            ->leftJoin('lebd_premium_class_packages as p','p.id','=','o.package_id')
            ->select('o.*','s.name as student_name','s.email as student_email','s.contact as student_contact','p.name as package_name')
            ->where('o.id',$order)->first();
        abort_unless($row,404);
        return view('admin.lebd-orders.show',compact('row'));
    }
}
